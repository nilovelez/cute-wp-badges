// Builds preview.html, a static table that draws every badge in
// data/badges.json with plain CSS, to check the catalog by eye.
// Usage: node scripts/build-preview.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const { badges } = JSON.parse(readFileSync(new URL('data/badges.json', root), 'utf8'));

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// SVG icons are inlined as data URLs so the page also works opened from disk.
const svgUrl = (name) => {
  const svg = readFileSync(new URL(`assets/icons/${name}.svg`, root), 'utf8').trim();
  return `url(&quot;data:image/svg+xml,${encodeURIComponent(svg)}&quot;)`;
};

const icon = ({ type, name }) =>
  type === 'dashicon'
    ? `<span class="icon dashicons dashicons-${esc(name)}"></span>`
    : `<span class="icon svg" style="--icon:${svgUrl(name)}"></span>`;

const row = (b) => `
      <tr>
        <td><span class="badge${b.isTeam ? ' is-team' : ''}" style="--badge-color:${b.color}">${icon(b.icon)}</span></td>
        <td>${esc(b.name)}</td>
        <td><code>${esc(b.id)}</code>${b.aliases.map((a) => `<br><code class="alias">${esc(a)}</code>`).join('')}</td>
        <td><a href="${esc(b.teamUrl)}">${esc(b.team)}</a></td>
        <td><code>${esc(b.wporgClass)}</code></td>
        <td><span class="swatch" style="background:${b.color}"></span><code>${b.color}</code></td>
        <td><code>${esc(b.icon.type === 'dashicon' ? `dashicons-${b.icon.name}` : `${b.icon.name}.svg`)}</code></td>
        <td>${b.isTeam ? 'Team' : 'Contributor'}</td>
        <td>${b.verified ? 'Yes' : '<span class="no">No</span>'}</td>
      </tr>`;

const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Badge Catalog Preview</title>
  <!-- Generated by scripts/build-preview.mjs from data/badges.json. Do not edit. -->
  <link rel="stylesheet" href="https://s.w.org/wp-includes/css/dashicons.min.css">
  <style>
    body { font: 14px/1.4 system-ui, sans-serif; margin: 24px; color: #1e1e1e; background: #fff; }
    table { border-collapse: collapse; }
    th, td { padding: 8px 12px; border-bottom: 1px solid #ddd; text-align: left; vertical-align: middle; }
    th { position: sticky; top: 0; background: #f6f7f7; }
    code { font-size: 12px; }
    .alias { color: #757575; }
    .no { color: #b32d2e; }
    .swatch { display: inline-block; width: 14px; height: 14px; border-radius: 3px; margin-right: 6px; vertical-align: -2px; }

    /* Old profile badge, scaled from the 32 px original: white circle with a
       2 px white border, a 4 px ring in the badge color and a 25% tint for team
       badges. Icon: 24 px Dashicon or 22 px SVG. */
    .badge {
      --s: 3;
      position: relative;
      display: inline-flex;
      align-items: center;
      justify-content: center;
      box-sizing: border-box;
      width: calc(32px * var(--s));
      height: calc(32px * var(--s));
      margin: calc(4px * var(--s));
      border: calc(2px * var(--s)) solid #fff;
      border-radius: 50%;
      background: #fff;
      box-shadow: 0 0 0 calc(4px * var(--s)) var(--badge-color);
    }
    .badge.is-team { background: color-mix(in srgb, var(--badge-color) 25%, #fff); }
    .badge .dashicons { width: auto; height: auto; font-size: calc(24px * var(--s)); color: var(--badge-color); }
    .badge .svg {
      width: calc(22px * var(--s));
      height: calc(22px * var(--s));
      background: var(--badge-color);
      mask: var(--icon) center / contain no-repeat;
      -webkit-mask: var(--icon) center / contain no-repeat;
    }
  </style>
</head>
<body>
  <h1>Badge catalog preview</h1>
  <p>${badges.length} badges from <code>data/badges.json</code>.</p>
  <table>
    <thead>
      <tr><th>Badge</th><th>Name</th><th>id / aliases</th><th>Team</th><th>WordPress.org class</th><th>Color</th><th>Icon</th><th>Type</th><th>Verified</th></tr>
    </thead>
    <tbody>${badges.map(row).join('')}
    </tbody>
  </table>
</body>
</html>
`;

writeFileSync(new URL('preview.html', root), html);
console.log(`preview.html: ${badges.length} badges`);
